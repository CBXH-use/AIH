const dicts: Record<'zh' | 'en', Dict> = { zh, en }

export function translate(lang: 'zh' | 'en', key: string, vars?: Record<string, string | number>): string {
  const raw = dicts[lang]?.[key] ?? dicts.zh[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

export function useT() {
  const lang = useAppStore((s) => s.settings.language || 'zh')
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars)
}
